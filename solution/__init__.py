"""Your solution.

The harness imports this package and calls `apply()` once, in the same process as `soup train`,
before Soup builds the model and the trainer. Patch whatever you need (transformers, peft,
bitsandbytes, Soup itself) so the training run uses your Triton kernels.

The rules in short (the README and the task statement have the full ones):
- your own `@triton.jit` kernels, defined in this folder, run in every measured run and together
  take >= 5% of the training time; the example's kernels (however renamed or rewritten) and
  kernels generated by torch.compile do not count;
- no ready-made kernel libraries (unsloth, liger-kernel, xformers, flash-attn, torchao, ...);
- the task stays the same: model, data, batches and their order, steps, LoRA, optimizer, Soup's
  settings and outputs; no other GPU, no background processes, no tricks with the measurement.
"""

def apply():
    from .swiglu import patch_qwen2_mlp
    from .rmsnorm import patch_qwen2_rmsnorm
    from .integration import patch_training_head
    from .settings import (
        FUSED_NF4, FROZEN_STORAGE, COMPACT_MLP_ACTIVATIONS,
        FUSED_ROTARY, FUSED_LORA_EPILOGUE, FUSED_LORA_DROPOUT,
        FUSED_RMSNORM, SHARED_ATTENTION_MASK,
    )

    if FUSED_NF4:
        from .nf4 import patch_bitsandbytes_nf4
        patch_bitsandbytes_nf4()
    if FROZEN_STORAGE:
        from .frozen_storage import patch_frozen_storage
        patch_frozen_storage()
    if FUSED_LORA_DROPOUT:
        from .lora_dropout import patch_lora_dropout
        patch_lora_dropout()
    if FUSED_LORA_EPILOGUE:
        from .lora_epilogue import patch_lora_epilogue
        patch_lora_epilogue()
    patch_qwen2_mlp()  # Explicitly credited starter example; not original work.
    if COMPACT_MLP_ACTIVATIONS:
        from .activation_storage import patch_compact_mlp_activations
        patch_compact_mlp_activations()
    if FUSED_RMSNORM:
        patch_qwen2_rmsnorm()
    if FUSED_ROTARY:
        from .rotary import patch_qwen2_rotary
        patch_qwen2_rotary()
    if SHARED_ATTENTION_MASK:
        from .shared_attention_mask import patch_shared_attention_mask
        patch_shared_attention_mask()
    patch_training_head()
