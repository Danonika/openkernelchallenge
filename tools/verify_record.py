def _finite(value, *, positive=False):
    return (isinstance(value, (int, float)) and not isinstance(value, bool)
            and math.isfinite(value) and (value > 0 if positive else True))


def _mapping(value):
    return value if isinstance(value, dict) else {}


def _same_number(value, expected):
    return _finite(value) and math.isclose(value, expected, rel_tol=1e-10, abs_tol=1e-9)


def _unique_object(pairs):
    value = {}
    for key, item in pairs:
        if key in value:
            raise ValueError(f"duplicate JSON key: {key}")
        value[key] = item
    return value


def _read(path):
    raw = Path(path).read_bytes()
    # Official JSON can contain an early GradScaler grad_norm=Infinity; that
    # diagnostic is not an admission gate. Required numbers are checked below.
    value = json.loads(raw, object_pairs_hook=_unique_object)
    if not isinstance(value, dict):
        raise ValueError("expected a JSON object")
    return value, hashlib.sha256(raw).hexdigest()


def _official_helpers(repo):
    # Verify code before importing it; no candidate solution module or CUDA
    # dependency is imported by this program.
    failures = []
    for name, expected in PROTECTED_SHA256.items():
        path = repo / name
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            failures.append(name)
    actual = {str(p.relative_to(repo)) for name in ("harness", "task", "tests")
              for p in (repo / name).rglob("*")
              if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"}
    failures.extend(sorted(actual - set(PROTECTED_SHA256)))
    if failures:
        raise ValueError("protected source differs from pinned starter: " + ", ".join(failures))
    spec = importlib.util.spec_from_file_location("_record_official_checks", repo / "harness/check_rules.py")
    module = importlib.util.module_from_spec(spec)
    # check_rules imports common by its historical top-level name. Temporarily
    # isolate that import so two fixture/checkouts cannot share the wrong REPO.
    saved_path, saved_common = list(sys.path), sys.modules.pop("common", None)
    try:
        spec.loader.exec_module(module)
    finally:
        sys.path[:] = saved_path
        sys.modules.pop("common", None)
        if saved_common is not None:
            sys.modules["common"] = saved_common
    return module


def verify_result(result_path, *, record_seconds=33.0, reference_baseline_seconds=None,
                  readiness_report=None, repo_root=None):
    repo = Path(repo_root or REPO).resolve()
    result_path = Path(result_path).resolve()
    report = {
        "schema_version": 1,
        "target_met_under_official_public_protocol": False,
        "passes_recorded_public_automatic_gates": False,
        "proven_world_record": False,
        "target_seconds": record_seconds if _finite(record_seconds) else None,
        "comparison": "official rounded median whole-command solution time strictly below target",
        "measurements": {},
        "provenance": {"starter_commit": STARTER_COMMIT, "result_file": str(result_path),
                       "per_run_source_hashes_recorded": False},
        "reasons": [],
        "limitations": [
            "Another team's timing protocol has not been authenticated; this is a target comparison, not a world-record claim.",
            "Hidden-row evaluation and the jury's manual review are not established by public automatic checks.",
            "The unchanged official harness uses fresh compiler caches, but result.json has no independent cache-state attestation.",
            "The official schema has no per-run source hashes; checks.json binds source at check time only.",
        ],
    }
    reasons = report["reasons"]
    if not _finite(record_seconds, positive=True):
        reasons.append("record_seconds must be positive and finite")
    if reference_baseline_seconds is not None:
        if not _finite(reference_baseline_seconds, positive=True):
            reasons.append("reference_baseline_seconds must be positive and finite")
        else:
            report["user_reported_reference_baseline_seconds"] = reference_baseline_seconds
    try:
        official = _official_helpers(repo)
        result, result_sha = _read(result_path)
        checks, checks_sha = _read(result_path.parent / "checks.json")
    except (OSError, ValueError, ImportError, SyntaxError) as exc:
        reasons.append(f"cannot verify official evidence: {exc}")
        return report
    provenance = report["provenance"]
    provenance.update(result_sha256=result_sha, checks_sha256=checks_sha, protected_source_matches=True)
    if checks.get("result_sha256") != result_sha:
        reasons.append("checks.json result_sha256 does not match the exact result.json bytes")
    if not (repo / "solution").is_dir():
        reasons.append("current solution/ is missing")
    current_sha = official.solution_sha256(repo / "solution")
    provenance.update(current_solution_sha256=current_sha, checked_solution_sha256=checks.get("solution_sha256"))
    if checks.get("solution_sha256") != current_sha:
        reasons.append("current solution source hash differs from checks.json solution_sha256")
    rows = checks.get("checks")
    if (not isinstance(rows, list) or len(rows) != official.CHECK_COUNT
            or tuple(_mapping(row).get("check") for row in rows) != CHECK_NAMES
            or any(_mapping(row).get("ok") is not True for row in rows)):
        reasons.append("all ten distinct official checks must be present, ordered, and explicitly true")
    elif re.search(rf"(?<!\d){official.EXPECTED_TESTS} passed\b", str(rows[-1].get("detail", ""))) is None:
        reasons.append("regression-test check does not record all 79 tests passing")
    task = _mapping(result.get("task"))
    repeat = task.get("repeats")
    if type(repeat) is not int or repeat < 2 or task.get("only") is not None:
        reasons.append("need at least two matched full base/solution runs, not --only or a single repeat")
    runs = _mapping(result.get("runs"))
    if set(runs) != {"base", "solution"}:
        reasons.append("result must contain base and solution run lists only")
    if result.get("packages_changed") != []:
        reasons.append("packages changed during measurement or that fact was not recorded")
    grouped, derived = {}, {}
    source = official.source_kernels(repo / "solution")
    own, _copies, _lookalikes, banned, broken = source
    if banned or broken:
        reasons.append(f"solution source has banned imports or parse errors: {banned + broken}")
    launched_sets = []
    evals = _mapping(result.get("evals"))
    for side in ("base", "solution"):
        side_runs = runs.get(side)
        if (not isinstance(side_runs, list) or len(side_runs) < 2
                or len(side_runs) != repeat or any(not isinstance(r, dict) for r in side_runs)):
            reasons.append(f"{side}: expected the declared number of at least two run records")
            grouped[side] = []
            continue
        grouped[side] = side_runs
        times, peaks, loops = [], [], []
        for index, run in enumerate(side_runs, 1):
            name = f"{side}_{index}"
            m = _mapping(run.get("metrics"))
            if run.get("run") != name or run.get("side") != side:
                reasons.append(f"{name}: run identity or side differs from official ordering")
            if (type(run.get("exit_code")) is not int or run["exit_code"] != 0
                    or type(m.get("exit_code")) is not int or m["exit_code"] != 0):
                reasons.append(f"{name}: run did not finish successfully")
            if m.get("solution") is not (side == "solution"):
                reasons.append(f"{name}: recorded solution activation does not match its side")
            wall, peak = run.get("wall_s"), run.get("gpu_peak_mib")
            if not _finite(wall, positive=True) or not _finite(peak, positive=True):
                reasons.append(f"{name}: wall time and sampled peak must be positive finite numbers")
            else:
                times.append(wall)
                peaks.append(peak)
            start, reserved = run.get("gpu_start_mib"), m.get("torch_max_reserved_mib")
            if not _finite(start) or not 0 <= start <= official.MAX_IDLE_START_MIB:
                reasons.append(f"{name}: GPUs were not recorded idle at start")
            if (not _finite(reserved, positive=True) or not _finite(peak, positive=True)
                    or peak < 0.97 * reserved):
                reasons.append(f"{name}: sampled GPU peak does not validate Torch reserved peak")
            if (not isinstance(m.get("cuda_device"), str) or not re.search(r"\bT4\b", m["cuda_device"])
                    or type(m.get("device_count")) is not int or m["device_count"] != 1
                    or m.get("visible_devices") != "0" or m.get("alloc_conf") != official.ALLOC_CONF
                    or m.get("alloc_conf_expected") != official.ALLOC_CONF):
                reasons.append(f"{name}: raw metrics do not establish one T4 with the official allocator")
            if m.get("steps") != 64 or run.get("global_step") != 64 or m.get("timed_steps") != 62:
                reasons.append(f"{name}: fixed 64-step task or step-3 timing window is missing")
            loop, timed = m.get("train_loop_s"), m.get("timed_loop_s")
            if not _finite(loop, positive=True) or not _finite(timed, positive=True):
                reasons.append(f"{name}: positive training-loop and timed-step durations are required")
            else:
                loops.append(loop)
                if timed > loop + 0.02 or (_finite(wall) and loop > wall + 0.02):
                    reasons.append(f"{name}: training-loop durations are inconsistent with wall time")
            if m.get("triton_watch_error") is not None:
                reasons.append(f"{name}: Triton launch monitoring reported an error")
            if side == "solution":
                if m.get("banned_modules_loaded") != []:
                    reasons.append(f"{name}: prohibited-module absence is not established")
                launches, files = _mapping(m.get("triton_launches")), _mapping(m.get("triton_files"))
                launched_sets.append({kernel for kernel, count in launches.items()
                                      if _finite(count, positive=True) and kernel in own
                                      and str(files.get(kernel, "")).replace("\\", "/") == own[kernel]})
        if len(times) == len(peaks) == len(loops) == len(side_runs):
            derived[side] = {"wall_s": round(statistics.median(times), 2),
                             "unrounded_median_wall_s": statistics.median(times),
                             "gpu_peak_mib": max(peaks), "runs": len(side_runs),
                             "train_loop_s": round(statistics.median(loops), 2)}
            summary = _mapping(_mapping(result.get("summary")).get(side))
            if summary.get("ok") is not True:
                reasons.append(f"{side}: summary is not marked successful")
            for key in ("wall_s", "gpu_peak_mib", "runs", "train_loop_s"):
                if not _same_number(summary.get(key), derived[side][key]):
                    reasons.append(f"{side}: summary {key} disagrees with raw runs")
        ev = _mapping(evals.get(side))
        loss = ev.get("mean_loss")
        if type(ev.get("exit_code")) is not int or ev["exit_code"] != 0 or not _finite(loss, positive=True):
            reasons.append(f"{side}: successful plain-adapter evaluation and finite positive loss are required")
        elif not _same_number(_mapping(_mapping(result.get("summary")).get(side)).get("eval_loss"), loss):
            reasons.append(f"{side}: summary eval_loss disagrees with evaluation")
    common_kernels = set.intersection(*launched_sets) if launched_sets else set()
    if not common_kernels or len(launched_sets) != len(grouped.get("solution", [])):
        reasons.append("no eligible original kernel is proven launched from the matching source in every solution run")
    shares = []
    for run in grouped.get("solution", []):
        m = _mapping(run.get("metrics"))
        times = _mapping(m.get("own_kernel_ms"))
        # The official observer counts launches before step 3 too. A genuine
        # setup/early-step kernel can lack a timed interval and contributes
        # zero, exactly as the official participation check does.
        if any(name in times and (not _finite(times[name]) or times[name] < 0) for name in common_kernels):
            reasons.append(f"{run.get('run')}: qualifying kernel timing is missing or invalid")
            continue
        timed = m.get("timed_loop_s")
        if _finite(timed, positive=True):
            share = sum(times.get(name, 0) for name in common_kernels) / (1000 * timed)
            shares.append(share)
            if share < official.MIN_KERNEL_SHARE:
                reasons.append(f"{run.get('run')}: original kernels account for less than 5% of timed step wall time")
    if grouped.get("base") and grouped.get("solution"):
        reference = grouped["base"][0]
        for run in grouped["base"][1:] + grouped["solution"]:
            try:
                differences = official.compare_outputs(reference, run)
                first, mean = official.compare_curves(reference, run)
                if differences:
                    reasons.append(f"{run.get('run')}: official output comparison failed: " + "; ".join(differences))
                if first is None or mean is None or first > official.MAX_FIRST_LOSS_DELTA or mean > official.MAX_CURVE_DELTA:
                    reasons.append(f"{run.get('run')}: official loss-curve comparison failed")
            except (KeyError, TypeError, ValueError) as exc:
                reasons.append(f"{run.get('run')}: malformed comparable outputs: {exc}")
    if set(derived) == {"base", "solution"}:
        base, sol = derived["base"], derived["solution"]
        speedup, memory_ratio = base["wall_s"] / sol["wall_s"], base["gpu_peak_mib"] / sol["gpu_peak_mib"]
        report["measurements"] = {"base": base, "solution": sol, "speedup_vs_paired_baseline": speedup,
                                  "memory_ratio_vs_paired_baseline": memory_ratio,
                                  "time_reduction_vs_paired_baseline_pct": 100 * (1 - sol["wall_s"] / base["wall_s"]),
                                  "lowest_eligible_kernel_share": min(shares) if shares else None}
        stated = _mapping(_mapping(result.get("summary")).get("ratios"))
        for key, ratio in (("speedup", speedup), ("memory_ratio", memory_ratio)):
            if not _same_number(stated.get(key), round(ratio, 4)):
                reasons.append(f"summary {key} disagrees with recalculated paired runs")
        if sol["wall_s"] > official.MAX_SLOWDOWN * base["wall_s"] or sol["gpu_peak_mib"] > official.MAX_MEMORY_GROWTH * base["gpu_peak_mib"]:
            reasons.append("solution violates the official 10% runtime or memory growth limit")
    base_loss, sol_loss = (_mapping(evals.get(side)).get("mean_loss") for side in ("base", "solution"))
    if _finite(base_loss, positive=True) and _finite(sol_loss, positive=True):
        quality = 100 * (sol_loss - base_loss) / base_loss
        report["measurements"]["eval_loss_delta_pct"] = quality
        if quality > official.MAX_QUALITY_DELTA_PCT:
            reasons.append("plain-adapter evaluation loss is more than 0.5% above the baseline")
        if not _same_number(_mapping(_mapping(result.get("summary")).get("ratios")).get("quality_delta_pct"), round(quality, 3)):
            reasons.append("summary quality delta disagrees with the evaluations")
    if readiness_report is not None:
        try:
            ready, ready_sha = _read(readiness_report)
            observed = Path(str(ready.get("official_result", "")))
            if not observed.is_absolute():
                observed = repo / observed
            valid = (ready.get("solution_sha256") == current_sha
                     and ready.get("status") == "public_official_checks_passed"
                     and _mapping(ready.get("protected_source")).get("ok") is True
                     and ready.get("official_checks_passed") is True
                     and observed.resolve() == result_path)
            provenance["readiness"] = {"report_sha256": ready_sha, "valid": valid,
                                       "source_kind": ready.get("source_kind", "not_recorded"),
                                       "source_evidence": "matching before/after source observation by readiness runner; no per-run hash attestation"}
            if not valid:
                reasons.append("supplied readiness report does not match this successful official run and source")
        except (OSError, ValueError) as exc:
            reasons.append(f"cannot validate supplied readiness report: {exc}")
    report["passes_recorded_public_automatic_gates"] = not reasons
    if not reasons and "solution" in derived and derived["solution"]["wall_s"] < record_seconds:
        report["target_met_under_official_public_protocol"] = True
    elif "solution" in derived and _finite(record_seconds) and derived["solution"]["wall_s"] >= record_seconds:
        reasons.append("solution median whole-command time is not strictly below the target; a tie does not qualify")
    # Preserve useful ordering while suppressing duplicated malformed-data errors.
    report["reasons"] = list(dict.fromkeys(reasons))
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("result", type=Path)
    parser.add_argument("--record-seconds", type=float, default=33.0)
    parser.add_argument("--reference-baseline-seconds", type=float)
    parser.add_argument("--readiness-report", type=Path)
    parser.add_argument("--output", type=Path, help="also write the verdict JSON; never overwrite official evidence or source")
    args = parser.parse_args(argv)
    try:
        report = verify_result(args.result, record_seconds=args.record_seconds,
                               reference_baseline_seconds=args.reference_baseline_seconds,
                               readiness_report=args.readiness_report)
    except Exception as exc:  # Fail closed on malformed evidence; never print a success traceback.
        report = {"target_met_under_official_public_protocol": False, "proven_world_record": False,
                  "reasons": [f"evidence verification failed: {type(exc).__name__}: {exc}"]}
    output_ok = True
    if args.output is not None:
        destination = args.output.resolve()
        evidence = {args.result.resolve(), args.result.resolve().parent / "checks.json"}
        if args.readiness_report is not None:
            evidence.add(args.readiness_report.resolve())
        protected = [REPO / name for name in ("solution", "harness", "task", "tests")]
        if destination in evidence or any(destination.is_relative_to(path.resolve()) for path in protected):
            report["reasons"].append("--output must not replace official evidence or protected/source files")
            output_ok = False
        else:
            try:
                destination.parent.mkdir(parents=True, exist_ok=True)
                temporary = destination.with_name(destination.name + ".tmp")
                temporary.write_text(json.dumps(report, indent=2, allow_nan=False) + "\n", encoding="utf-8")
                temporary.replace(destination)
            except OSError as exc:
                report["reasons"].append(f"cannot save requested verdict: {exc}")
                output_ok = False
    print(json.dumps(report, indent=2, allow_nan=False))
    return 0 if report["target_met_under_official_public_protocol"] and output_ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
