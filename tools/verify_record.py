"""Check a runtime target against completed, unchanged official Soup results.

    python tools/verify_record.py runs/final/result.json --record-seconds 33
    python tools/verify_record.py runs/final/result.json --record-seconds 33 \
        --reference-baseline-seconds 77 --readiness-report runs/readiness/readiness.json

This read-only verifier does not run training, repair results, extrapolate GPU
performance, or establish a world record. It checks recorded public automatic
gates and a strict whole-command timing target. Hidden-row admission and the
protocol of another team's result remain outside its evidence.
"""

